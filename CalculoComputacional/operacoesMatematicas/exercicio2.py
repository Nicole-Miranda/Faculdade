from math import pow

a = 4
b = 5

a_elevado_ao_quadrado = pow(a,2)
a_elevado_ao_cubo = pow(a,3)
a_elevado_a_quarta = pow(a,4)
a_elevado_a_b = pow(a,b)

print('a elevado ao quadrado =', a_elevado_ao_quadrado)
print('a elevado ao cubo =', a_elevado_ao_cubo)
print('a elevado a quarta =', a_elevado_a_quarta)
print('a elevado a b =', a_elevado_a_b)
